// Shared TypeScript type generator for the npm workspaces (web, sdk/ts).
// Called by each workspace's scripts/generate.mjs through `make generate`.

import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { compileFromFile } from "json-schema-to-typescript";
import openapiTS, { astToString } from "openapi-typescript";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** Directory with the schema/*.v1.json files. */
export const schemaDir = path.join(repoRoot, "schema");

/** OpenAPI contract of the core API. */
export const openapiFile = path.join(repoRoot, "api", "openapi.json");

const schemaSuffix = ".v1.json";

/** Banner placed at the top of every generated file. */
function banner(source) {
  return [
    "/**",
    ` * Generated by \`make generate\` from ${source}.`,
    " * Do not edit this file by hand; change the source and regenerate.",
    " */",
  ].join("\n");
}

/** Lists the schema names (file name without ".v1.json"), sorted. */
export async function listSchemas() {
  const entries = await readdir(schemaDir);
  return entries
    .filter((name) => name.endsWith(schemaSuffix))
    .map((name) => name.slice(0, -schemaSuffix.length))
    .sort();
}

/** "check-result" -> "checkResult" */
export function toIdentifier(name) {
  return name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
}

/**
 * Maps every schema's "$id" (without fragment) to its local file, so cross-schema
 * references resolve from disk and never over the network.
 */
async function localSchemaResolver() {
  const byId = new Map();
  for (const name of await listSchemas()) {
    const file = path.join(schemaDir, name + schemaSuffix);
    const schema = JSON.parse(await readFile(file, "utf8"));
    if (typeof schema.$id === "string") {
      byId.set(schema.$id.split("#")[0], file);
    }
  }
  const key = (url) => String(url).split("#")[0];
  return {
    order: 1,
    canRead: (file) => byId.has(key(file.url)),
    read: (file) => readFile(byId.get(key(file.url)), "utf8"),
  };
}

/** Removes previously generated *.ts files (keeps .gitkeep). */
async function cleanOutDir(outDir) {
  await mkdir(outDir, { recursive: true });
  for (const entry of await readdir(outDir)) {
    if (entry.endsWith(".ts")) {
      await rm(path.join(outDir, entry));
    }
  }
}

/**
 * Generates TypeScript types.
 *
 * @param {object} options
 * @param {string} options.outDir Target directory (cleaned before generation).
 * @param {string[]} [options.schemas] Schema names to generate; defaults to all.
 * @param {boolean} [options.openapi] Also generate api.ts from api/openapi.json (skipped while it does not exist).
 * @param {boolean} [options.index] Also write index.ts re-exporting each module as a namespace.
 */
export async function generate({ outDir, schemas, openapi = false, index = false }) {
  const names = schemas ?? (await listSchemas());
  const resolver = await localSchemaResolver();
  await cleanOutDir(outDir);

  for (const name of names) {
    const file = path.join(schemaDir, name + schemaSuffix);
    const ts = await compileFromFile(file, {
      cwd: schemaDir,
      bannerComment: banner(`schema/${name}${schemaSuffix}`),
      additionalProperties: false,
      unreachableDefinitions: true,
      $refOptions: { resolve: { http: false, devbox: resolver } },
    });
    await writeFile(path.join(outDir, `${name}.ts`), ts);
    console.log(
      `json2ts            schema/${name}${schemaSuffix} -> ${path.relative(repoRoot, outDir)}/${name}.ts`,
    );
  }

  if (openapi && existsSync(openapiFile)) {
    const ast = await openapiTS(pathToFileURL(openapiFile));
    const ts = `${banner("api/openapi.json")}\n\n${astToString(ast)}`;
    await writeFile(path.join(outDir, "api.ts"), ts);
    console.log(`openapi-typescript api/openapi.json -> ${path.relative(repoRoot, outDir)}/api.ts`);
  }

  if (index) {
    const lines = names.map((name) => `export * as ${toIdentifier(name)} from "./${name}.js";`);
    const ts = `${banner("the schema files")}\n\n${lines.join("\n")}\n`;
    await writeFile(path.join(outDir, "index.ts"), ts);
  }
}
